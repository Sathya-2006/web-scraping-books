import pandas as pd
import sqlite3
from io import StringIO

# 1. Extract sample property data
raw_data = """property_id,city,price,area_sqft
101,Chennai,4500000,1200
102,Bangalore,7500000,1500
103,Chennai,,900
104,Hyderabad,6200000,1100
102,Bangalore,7500000,1500
105,Chennai,-200000,800
106,Mumbai,9000000,0
"""

df = pd.read_csv(StringIO(raw_data))
print("Raw rows:", len(df))

# 2. Transform and validate with Pandas
df = df.drop_duplicates()

df["price"] = pd.to_numeric(df["price"], errors="coerce")
df["area_sqft"] = pd.to_numeric(
    df["area_sqft"], errors="coerce"
)

clean_df = df.dropna(
    subset=["property_id", "city", "price", "area_sqft"]
).copy()

clean_df = clean_df[
    (clean_df["price"] > 0) &
    (clean_df["area_sqft"] > 0)
].copy()

# 3. Load into SQLite
conn = sqlite3.connect("properties.db")

clean_df.to_sql(
    "properties",
    conn,
    if_exists="replace",
    index=False
)

print("Valid rows loaded:", len(clean_df))

# 4. SQL data quality checks
quality_sql = """
SELECT
    COUNT(*) AS total_rows,
    COUNT(DISTINCT property_id) AS unique_ids,
    SUM(CASE WHEN price <= 0 THEN 1 ELSE 0 END)
        AS invalid_prices,
    SUM(CASE WHEN area_sqft <= 0 THEN 1 ELSE 0 END)
        AS invalid_areas
FROM properties;
"""

print("\nSQL quality report:")
print(pd.read_sql_query(quality_sql, conn))

# 5. Business analysis: average price by city
city_sql = """
SELECT
    city,
    COUNT(*) AS property_count,
    ROUND(AVG(price), 2) AS average_price
FROM properties
GROUP BY city
ORDER BY average_price DESC;
"""

print("\nCity-wise property analysis:")
print(pd.read_sql_query(city_sql, conn))

conn.close()

